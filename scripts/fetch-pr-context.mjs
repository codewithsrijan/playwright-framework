#!/usr/bin/env node
/**
 * Fetches PR metadata via GitHub CLI and writes specs/pr-<number>-context.md
 * for use with Cursor / planner prompts.
 *
 * Prerequisites: gh installed and authenticated (`gh auth login`).
 * Enterprise: set GH_HOST (e.g. github.skillsoft.com) if your org requires it.
 *
 * Usage:
 *   node scripts/fetch-pr-context.mjs <pr-number> [owner/repo]
 *   npm run fetch-pr-context -- 8783 HardRoc/ucm2
 *
 * Env:
 *   GH_HOST     - GitHub Enterprise hostname (optional)
 *   GH_REPO     - Default owner/repo if not passed as second arg (optional)
 */

import { execFileSync } from "child_process";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.join(__dirname, "..");

const prNumber = process.argv[2];
const repoArg = process.argv[3];
const defaultRepo = process.env.GH_REPO || "HardRoc/ucm2";
const repo = repoArg || defaultRepo;

if (!prNumber || !/^\d+$/.test(prNumber)) {
  console.error(
    "Usage: node scripts/fetch-pr-context.mjs <pr-number> [owner/repo]",
  );
  console.error("Example: npm run fetch-pr-context -- 8783 HardRoc/ucm2");
  process.exit(1);
}

function gh(args) {
  const out = execFileSync("gh", args, {
    encoding: "utf8",
    env: { ...process.env },
    stdio: ["ignore", "pipe", "pipe"],
  });
  return out;
}

let json;
try {
  const raw = gh([
    "pr",
    "view",
    prNumber,
    "--repo",
    repo,
    "--json",
    "title,body,url,number,author,files,additions,deletions,state",
  ]);
  json = JSON.parse(raw);
} catch (e) {
  console.error("gh failed. Install GitHub CLI and run: gh auth login");
  if (process.env.GH_HOST) {
    console.error(`GH_HOST is set to: ${process.env.GH_HOST}`);
  } else {
    console.error(
      "For GitHub Enterprise, try: export GH_HOST=github.skillsoft.com",
    );
  }
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
}

const files = (json.files || [])
  .map((f) => f.path)
  .filter(Boolean)
  .join("\n");

const author = json.author?.login || json.author?.name || "unknown";

const md = `<!-- Generated by scripts/fetch-pr-context.mjs — safe to edit below -->

# PR #${json.number}: ${json.title}

**State:** ${json.state}  
**URL:** ${json.url}  
**Repo:** ${repo}  
**Author:** ${author}  
**Additions / deletions:** +${json.additions ?? "?"} / -${json.deletions ?? "?"}

## Description

${json.body?.trim() || "_No description._"}

## Changed files

\`\`\`
${files || "(none listed)"}
\`\`\`

---

## App URL (fill in for Playwright planner)

**Development / preview URL:** \`<!-- paste e.g. https://ucm2.develop.squads-dev.com/ -->\`  
*(Replace with your preview URL if different.)*

## Cursor prompt (paste into Agent)

Follow \`.cursor/rules/playwright-agents.mdc\`: use the **PR prompt template**, then **planner** (save plan under \`specs/\`), then **generator** (Playwright tests).

- **App URL:** (copy from **Development / preview URL** above)
- **PR context:** \`@specs/pr-${prNumber}-context.md\` (this file — description, changed files, PR link)
`;

const outPath = path.join(repoRoot, "specs", `pr-${prNumber}-context.md`);
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, md, "utf8");

console.log(`Wrote ${outPath}`);
